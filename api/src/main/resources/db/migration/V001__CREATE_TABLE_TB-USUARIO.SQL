CREATE TABLE IF NOT EXISTS TB_USUARIO (
    CODE BIGSERIAL NOT NULL,
    CODE_PUBLIC UUID NOT NULL DEFAULT GEN_RANDOM_UUID(),
    PERFIL VARCHAR(255) NOT NULL,
    NOME VARCHAR(255) NOT NULL,
    IDENTIFICADOR VARCHAR(255) NOT NULL,
    CHAVE_ACESSO VARCHAR(255) NOT NULL,
    CHAVE_ACESSO_ANTERIOR VARCHAR(255) NULL,
    TOKEN VARCHAR(400) NULL,
    REFRESH_TOKEN VARCHAR(400) NULL,
    HASH_CADASTRO VARCHAR(255) NOT NULL,
    IS_CONTA_VERIFICADA BOOLEAN NOT NULL DEFAULT FALSE,
    CREATED_AT TIMESTAMP NOT NULL DEFAULT NOW(),
    UPDATED_AT TIMESTAMP NULL,
    DELETED_AT TIMESTAMP NULL,
    IS_ACTIVE BOOLEAN NOT NULL DEFAULT TRUE,
    CONSTRAINT PK_USUARIO PRIMARY KEY (CODE),
    CONSTRAINT UN_USUARIO UNIQUE (PERFIL, IDENTIFICADOR)
);
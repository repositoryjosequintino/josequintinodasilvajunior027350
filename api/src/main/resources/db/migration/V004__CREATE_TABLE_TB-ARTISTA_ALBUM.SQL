CREATE TABLE IF NOT EXISTS TB_ARTISTA_ALBUM (
	CODE BIGSERIAL NOT NULL,
	CODE_PUBLIC UUID NOT NULL DEFAULT GEN_RANDOM_UUID(),
	ID_ARTISTA BIGINT NOT NULL,
	ID_ALBUM BIGINT NOT NULL,
	CREATED_AT TIMESTAMP NOT NULL DEFAULT NOW(),
	UPDATED_AT TIMESTAMP NULL,
	DELETED_AT TIMESTAMP NULL,
	IS_ACTIVE BOOLEAN NOT NULL DEFAULT TRUE,
	CONSTRAINT PK_ALBUM_ARTISTA PRIMARY KEY (CODE),
	CONSTRAINT FK_ALBUM_ARTISTA_1 FOREIGN KEY (ID_ARTISTA) REFERENCES TB_ARTISTA (CODE),
	CONSTRAINT FK_ALBUM_ARTISTA_2 FOREIGN KEY (ID_ALBUM) REFERENCES TB_ALBUM (CODE),
	CONSTRAINT UN_ARTISTA_ALBUM UNIQUE (ID_ARTISTA, ID_ALBUM)
);
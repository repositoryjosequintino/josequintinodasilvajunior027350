CREATE TABLE IF NOT EXISTS TB_ALBUM_ARQUIVO (
    CODE BIGSERIAL NOT NULL,
    CODE_PUBLIC UUID NOT NULL DEFAULT GEN_RANDOM_UUID(),
    ID_ARQUIVO BIGINT NOT NULL,
    ID_ALBUM BIGINT NOT NULL,
    IS_ARQUIVO_PRINCIPAL BOOLEAN NOT NULL DEFAULT TRUE,
    CREATED_AT TIMESTAMP NOT NULL DEFAULT NOW(),
    UPDATED_AT TIMESTAMP NULL,
    DELETED_AT TIMESTAMP NULL,
    IS_ACTIVE BOOLEAN NOT NULL DEFAULT TRUE,
    CONSTRAINT PK_ALBUM_ARQUIVO PRIMARY KEY (CODE),
    CONSTRAINT FK_ALBUM_ARQUIVO_1 FOREIGN KEY (ID_ARQUIVO) REFERENCES TB_ARQUIVO (CODE),
    CONSTRAINT FK_ALBUM_ARQUIVO_2 FOREIGN KEY (ID_ALBUM) REFERENCES TB_ALBUM (CODE),
    CONSTRAINT UN_ALBUM_ARQUIVO UNIQUE (ID_ARQUIVO, ID_ALBUM)
);